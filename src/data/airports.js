const BY_CODE = new Map(AIRPORTS.map((a) => [a[0], a]))

/** "BLR · Bengaluru — Kempegowda International" (what the input shows). */
export const airportLabel = (code) => {
  const a = BY_CODE.get(code)
  return a ? `${a[0]} · ${a[1]} — ${a[2]}` : code
}

export const cityOf = (code) => BY_CODE.get(code)?.[1] || code
export const countryOf = (code) => BY_CODE.get(code)?.[3] || null

/** Typed text → IATA code, if we can tell. Accepts "BLR", "blr", a city name or a full label. */
export function codeFromText(text) {
  const t = String(text || '').trim()
  const lead = t.match(/^([A-Za-z]{3})\b/)
  if (lead && BY_CODE.has(lead[1].toUpperCase())) return lead[1].toUpperCase()
  const city = AIRPORTS.find((a) => a[1].toLowerCase() === t.toLowerCase())
  if (city) return city[0]
  return /^[A-Za-z]{3}$/.test(t) ? t.toUpperCase() : null
}
